"""The app starts, talks to the database, and the schema matches the models."""
import os

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from tests.conftest import HERE


def test_status_page_renders(app):
    resp = app.get("/")
    assert resp.status_int == 200
    assert "Database: ok" in resp.text


def test_health_reports_database(app):
    assert app.get("/health").json == {"status": "ok", "database": True}


def test_migrations_match_models(migrated_db):
    try:
        command.check(Config(os.path.join(HERE, "alembic.ini")))
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - shows the diff
        raise AssertionError("Alembic migration and models differ: %s" % exc)
