"""The app starts, talks to the database, the schema matches the models, and it
reports its version."""
import os
import re

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from bingarde import __version__
from tests.conftest import HERE


def test_root_redirects_to_build_list(anon):
    resp = anon.get("/", status=302)
    assert resp.location.endswith("/builds")


def test_health_reports_database_storage_and_version(app):
    assert app.get("/health").json == {"status": "ok", "database": True, "storage": True,
                                      "version": __version__}


def test_version_is_semver():
    assert re.fullmatch(r"\d+\.\d+\.\d+", __version__)


def test_api_responses_carry_the_version(app, anon):
    assert app.get("/api/v2/builds").headers["X-Bingarde-Version"] == __version__
    error = app.get("/api/v2/builds/999999", status=404)
    assert error.headers["X-Bingarde-Version"] == __version__
    assert anon.get("/api/v2/builds", status=401).headers["X-Bingarde-Version"] == __version__


def test_pages_show_the_version_in_the_footer(anon):
    page = anon.get("/login").text
    assert re.search(r'id="id-footer">\s*Bingarde %s\s*</footer>' % re.escape(__version__), page)


def test_migrations_match_models(migrated_db):
    try:
        command.check(Config(os.path.join(HERE, "alembic.ini")))
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - shows the diff
        raise AssertionError("Alembic migration and models differ: %s" % exc)
